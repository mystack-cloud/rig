#!/bin/bash

# End-to-End Test Script for Hetzner S3-Compatible Storage
# This script tests the complete workflow using the Hetzner Cloud API token

echo "Starting End-to-End Test for Hetzner S3-Compatible Storage"

# Check if .env file exists
if [ ! -f ".env" ]; then
    echo "Error: .env file not found. Please create .env with HETZNER_CLOUD_API_TOKEN."
    exit 1
fi

# Load environment variables
source .env

# Verify that the token is set
if [ -z "$HETZNER_CLOUD_API_TOKEN" ]; then
    echo "Error: HETZNER_CLOUD_API_TOKEN not found in .env file"
    exit 1
fi

echo "Using Hetzner Cloud API token (masked for security): ${HETZNER_CLOUD_API_TOKEN:0:4}****${HETZNER_CLOUD_API_TOKEN: -4}"

# Set the environment variable for the CLI
export HZ_TOKEN=$HETZNER_CLOUD_API_TOKEN
export S3_ENDPOINT_URL="https://fsn1.your-objectstorage.com"

# Create a unique test bucket name to avoid conflicts
TIMESTAMP=$(date +%s)
TEST_BUCKET="test-bucket-${TIMESTAMP}"
SHARED_BUCKET="shared-state-bucket-${TIMESTAMP}"

echo ""
echo "=== E2E TEST STARTED ==="
echo "Test bucket name: $TEST_BUCKET"
echo "Shared bucket name: $SHARED_BUCKET"

# Function to cleanup on exit
cleanup() {
    echo ""
    echo "Cleaning up test resources..."
    # Delete test bucket if it exists
    python3 src/cli/main.py storage delete-bucket --name "$TEST_BUCKET" 2>/dev/null || true
    # Delete shared bucket if it exists  
    python3 src/cli/main.py storage delete-bucket --name "$SHARED_BUCKET" 2>/dev/null || true
    # Clean up local files
    rm -f test_state_file.txt downloaded_state.json shared_state.txt downloaded_shared_state.json
    echo "Cleanup completed."
}

# Set trap to cleanup on exit
trap cleanup EXIT

echo ""
echo "=== TEST 1: Basic Storage Operations ==="

echo "1. Testing list buckets..."
python3 src/cli/main.py storage list-buckets

echo ""
echo "2. Testing create bucket..."
python3 src/cli/main.py storage create-bucket --name "$TEST_BUCKET"

echo ""
echo "3. Testing upload file..."
# Create a test file
echo "This is test file content for environment state." > test_state_file.txt
python3 src/cli/main.py storage upload \
  --bucket "$TEST_BUCKET" \
  --file test_state_file.txt \
  --object-name "development_env/state.json"

echo ""
echo "4. Testing list objects..."
python3 src/cli/main.py storage list-objects \
  --bucket "$TEST_BUCKET"

echo ""
echo "5. Testing download file..."
python3 src/cli/main.py storage download \
  --bucket "$TEST_BUCKET" \
  --object "development_env/state.json" \
  --file downloaded_state.json

echo ""
echo "6. Testing delete object..."
python3 src/cli/main.py storage delete-object \
  --bucket "$TEST_BUCKET" \
  --object "development_env/state.json"

echo ""
echo "7. Testing delete bucket..."
python3 src/cli/main.py storage delete-bucket --name "$TEST_BUCKET"

echo ""
echo "=== TEST 2: Shared State Management ==="

echo "1. Creating shared state bucket..."
python3 src/cli/main.py storage create-bucket --name "$SHARED_BUCKET"

echo "2. Uploading shared state..."
echo "Shared state data for all environments" > shared_state.txt
python3 src/cli/main.py storage upload \
  --bucket "$SHARED_BUCKET" \
  --file shared_state.txt \
  --object-name "shared_state.json"

echo "3. Listing shared objects..."
python3 src/cli/main.py storage list-objects \
  --bucket "$SHARED_BUCKET"

echo "4. Downloading shared state..."
python3 src/cli/main.py storage download \
  --bucket "$SHARED_BUCKET" \
  --object "shared_state.json" \
  --file downloaded_shared_state.json

echo "5. Deleting shared state object..."
python3 src/cli/main.py storage delete-object \
  --bucket "$SHARED_BUCKET" \
  --object "shared_state.json"

echo "6. Deleting shared state bucket..."
python3 src/cli/main.py storage delete-bucket --name "$SHARED_BUCKET"

echo ""
echo "=== TEST COMPLETED SUCCESSFULLY ==="
echo "Note: S3 credentials are generated by Hetzner and shown only once."
echo "      State files were stored and retrieved from Hetzner S3-compatible storage."

# Demonstrate dynamic key generation (this would normally be handled by Hetzner API)
echo ""
echo "=== DYNAMIC KEY GENERATION DEMONSTRATION ==="
echo "In a real implementation, access keys and secret keys would be:"
echo "1. Generated on-the-fly for each session using Hetzner API"
echo "2. Old keys would be deleted automatically when new ones are created"
echo "3. Keys would have limited lifetime (typically hours)"